import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('product navigation works as a mobile disclosure across Home, Library, Settings and setup', async ({ page }) => {
  test.setTimeout(180000)
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
  await page.request.post('/api/auth/dev-session', { data: { scenario: 'member' } })
  await page.addInitScript(() => {
    (window as any).__menuMicRequests = 0
    Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: async () => {
      (window as any).__menuMicRequests++
      throw new Error('Navigation must not request a microphone')
    } } })
  })
  const header = page.locator('.air-app-header')
  const navigation = page.getByRole('navigation', { name: 'Flowst Airs navigation', exact: true })
  const trigger = header.locator('.air-product-menu-trigger')
  const labels = ['Home', 'New session', 'Library', 'Settings']
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/home?from=menu')
  await expect(navigation).toBeVisible({ timeout: 90000 })
  await expect(trigger).toBeHidden()
  await expect(navigation.getByRole('link', { name: 'Home', exact: true })).toHaveAttribute('aria-current', 'page')

  for (const width of [320, 393, 768, 844]) {
    await page.setViewportSize({ width, height: 851 })
    await expect(trigger).toBeVisible()
    await expect(trigger).toBeEnabled()
    await expect(navigation).toBeHidden()
    await trigger.locator('svg').click()
    await expect(trigger).toHaveAttribute('aria-expanded', 'true')
    await expect(navigation).toBeVisible()
    await expect(navigation.getByRole('link')).toHaveText(labels)
    await expect(navigation.getByRole('link', { name: 'Home', exact: true })).toBeFocused()
    const bounds = await navigation.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).include('.air-app-header').analyze()).violations).toEqual([])
    if (width === 393) await page.screenshot({ path: test.info().outputPath('product-menu-open.png') })
    await page.keyboard.press('Escape')
    await expect(navigation).toBeHidden()
    await expect(trigger).toBeFocused()
  }

  await page.setViewportSize({ width: 393, height: 851 })
  await trigger.click()
  await page.mouse.click(2, 280)
  await expect(navigation).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.locator('#main-content').focus()
  await expect(navigation).toBeHidden()
  await expect(page.locator('#main-content')).toBeFocused()

  for (const [label, path] of [['Library', '/home/library'], ['Settings', '/home/settings'], ['New session', '/home/new'], ['Home', '/home']]) {
    await trigger.click()
    await navigation.getByRole('link', { name: label, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(path + '$'))
    await expect(trigger).toBeVisible()
    await expect(trigger).toHaveAttribute('aria-expanded', 'false')
    await expect(navigation).toBeHidden()
    await trigger.click()
    await expect(navigation.getByRole('link', { name: label, exact: true })).toHaveAttribute('aria-current', 'page')
    await page.keyboard.press('Escape')
  }
  await trigger.click()
  await navigation.getByRole('link', { name: 'New session', exact: true }).click()
  const account = header.locator('.air-account summary')
  await account.focus()
  await expect(account).toBeFocused()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(account).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(navigation).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 393, height: 851 })
  await account.click()
  const signOut = header.getByRole('button', { name: 'Sign out', exact: true })
  await signOut.focus()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(signOut).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(header.locator('.air-account')).not.toHaveAttribute('open')
  await trigger.click()
  await navigation.getByRole('link', { name: 'Home', exact: true }).click()
  await page.setViewportSize({ width: 393, height: 851 })
  await trigger.click()
  await header.locator('.air-account summary').click()
  await expect(navigation).toBeHidden()
  await expect(header.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
  await trigger.click()
  await expect(header.getByRole('button', { name: 'Sign out', exact: true })).toBeHidden()
  await expect(navigation).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(trigger).toBeHidden()
  await expect(navigation).toBeVisible()
  await page.setViewportSize({ width: 393, height: 851 })
  await expect(navigation).toBeHidden()
  await expect(trigger).toBeFocused()
  await account.click()
  await signOut.focus()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(signOut).toBeVisible()
  await expect(signOut).toBeFocused()
  expect(await page.evaluate(() => (window as any).__menuMicRequests)).toBe(0)
})
